def check_colmap_available():
    """Check if COLMAP CLI is available.

    Returns:
        str: Path to COLMAP executable

    Raises:
        COLMAPNotFoundError: If COLMAP is not found
    """
    # 1. on PATH (the user's interactive shell may have it even if this
    #    subprocess's environment does not resolve it as a bare command)
    colmap_exe = shutil.which("colmap")
    if colmap_exe:
        return colmap_exe

    # 2. directly invocable (e.g. PATH resolves it for the child process)
    try:
        result = subprocess.run(
            ['colmap', '--version'],
            capture_output=True,
            text=True,
            timeout=5,
        )
        if result.returncode == 0:
            print(f"Found COLMAP: {result.stdout.strip()}")
            return 'colmap'
    except (subprocess.TimeoutExpired, FileNotFoundError):
        pass

    # Try common Windows installation paths
    if sys.platform == 'win32':
        common_paths = [
            r"C:\Program Files\Colmap\bin\colmap.bat",
            r"C:\Program Files (x86)\Colmap\bin\colmap.bat",
            Path.home() / "scoop" / "apps" / "colmap" / "current" / "bin" / "colmap.bat",
        ]
        for path in common_paths:
            if Path(path).exists():
                print(f"Found COLMAP at: {path}")
                return str(path)

    raise COLMAPNotFoundError(
        "COLMAP not found. Please install COLMAP from https://colmap.github.io/install.html\n"
        "  Windows: Download installer or use scoop (scoop install colmap)\n"
        "  Linux: sudo apt install colmap\n"
        "  macOS: brew install colmap"
    )


