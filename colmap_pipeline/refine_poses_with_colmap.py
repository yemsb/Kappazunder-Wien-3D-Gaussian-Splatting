def _camera_center(qvec, tvec):
    """Camera projection center C = -R^T @ t from quaternion (wxyz) + tvec."""
    qw, qx, qy, qz = qvec
    R = np.array([
        [1 - 2 * (qy * qy + qz * qz), 2 * (qx * qy - qz * qw), 2 * (qx * qz + qy * qw)],
        [2 * (qx * qy + qz * qw), 1 - 2 * (qx * qx + qz * qz), 2 * (qy * qz - qx * qw)],
        [2 * (qx * qz - qy * qw), 2 * (qy * qz + qx * qw), 1 - 2 * (qx * qx + qy * qy)],
    ], dtype=np.float64)
    return -R.T @ tvec


def compute_pose_statistics(original_sparse_dir, refined_sparse_dir):
    """Compute statistics on pose refinement (matched by image name).

    Compares camera projection centers (world coordinates) to isolate
    translation from rotation changes.
    """
    orig = _parse_images_txt(original_sparse_dir / "images.txt")
    refined = _parse_images_txt(refined_sparse_dir / "images.txt")

    orig_by_name = {row["name"]: row for row in orig}
    refined_by_name = {row["name"]: row for row in refined}

    deviations = []
    for name, orig_row in orig_by_name.items():
        ref_row = refined_by_name.get(name)
        if ref_row is None:
            continue
        orig_center = _camera_center(orig_row["qvec"], orig_row["tvec"])
        ref_center = _camera_center(ref_row["qvec"], ref_row["tvec"])
        deviations.append(np.linalg.norm(orig_center - ref_center))

    n_orig = len(orig)
    n_ref = len(refined)
    n_matched = len(deviations)

    if n_matched == 0:
        return {
            "num_original": n_orig,
            "num_refined": n_ref,
            "num_matched": 0,
            "mean_deviation_m": 0.0,
            "median_deviation_m": 0.0,
            "max_deviation_m": 0.0,
            "min_deviation_m": 0.0,
        }

    return {
        "num_original": n_orig,
        "num_refined": n_ref,
        "num_matched": n_matched,
        "mean_deviation_m": float(np.mean(deviations)),
        "median_deviation_m": float(np.median(deviations)),
        "max_deviation_m": float(np.max(deviations)),
        "min_deviation_m": float(np.min(deviations)),
    }


def save_refined_output(dataset_dir, refined_txt_dir, lidar_ply_path):
    """Save refined output to dataset_dir/sparse_refined/0."""
