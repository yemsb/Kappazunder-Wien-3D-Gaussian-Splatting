def load_scene_origin(scene_origin_path):
    """Load the scene origin offset from scene_origin.txt.

    Args:
        scene_origin_path: Path to scene_origin.txt

    Returns:
        tuple: (offset_x, offset_y, offset_z, invert_y_axis)
    """
    with open(scene_origin_path, 'r') as f:
        lines = f.readlines()

    # Parse key-value pairs (skip comment lines starting with #)
    values = {}
    for line in lines:
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        parts = line.split()
        if len(parts) >= 2:
            values[parts[0]] = parts[1]

    offset_x = float(values['offset_x_m'])
    offset_y = float(values['offset_y_m'])
    offset_z = float(values['offset_z_m'])

    # invert_y_axis may be absent; default to 0 (false)
    invert_y = bool(int(values.get('invert_y_axis', '0')))

    return offset_x, offset_y, offset_z, invert_y


def setup_workspace(dataset_dir, config):
    """Create COLMAP workspace directory.

    Args:
        dataset_dir: Path to dataset output directory
        config: Configuration dictionary

    Returns:
        Path: Workspace directory path
    """
    workspace = dataset_dir / "colmap_workspace"

