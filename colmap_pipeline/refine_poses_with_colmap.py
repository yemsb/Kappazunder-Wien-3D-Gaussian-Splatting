def _parse_cameras_txt(cameras_path):
    """Parse COLMAP cameras.txt into {camera_id: (model, width, height, params[])}."""
    cameras = {}
    with open(cameras_path, 'r') as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('#'):
                continue
            parts = line.split()
            camera_id = int(parts[0])
            model = parts[1].upper()
            width = int(parts[2])
            height = int(parts[3])
            params = [float(p) for p in parts[4:]]
            cameras[camera_id] = (model, width, height, params)
    return cameras


def _parse_images_txt(images_path):
    """Parse COLMAP images.txt into a list of image pose rows.

    Returns list of dicts: image_id, qvec(wxyz), tvec, camera_id, name
    """
    images = []
    with open(images_path, 'r') as f:
        lines = [l.strip() for l in f if l.strip() and not l.startswith('#')]
    for i in range(0, len(lines), 2):  # every other line (skip the POINTS2D row)
        parts = lines[i].split()
        images.append({
            "image_id": int(parts[0]),
            "qvec": np.array([float(v) for v in parts[1:5]]),   # w, x, y, z
            "tvec": np.array([float(v) for v in parts[5:8]]),
            "camera_id": int(parts[8]),
            "name": parts[9],
        })
    return images


CAMERA_MODEL_TO_ID = {
    "SIMPLE_PINHOLE": 0,
    "PINHOLE": 1,
    "SIMPLE_RADIAL": 2,
    "RADIAL": 3,
    "OPENCV": 4,
    "OPENCV_FISHEYE": 5,
    "FULL_OPENCV": 6,
    "FOV": 7,
    "SIMPLE_RADIAL_FISHEYE": 8,
    "RADIAL_FISHEYE": 9,
    "THIN_PRISM_FISHEYE": 10,
    "SIMPLE_CAMERA": 11,
}

SENSOR_TYPE_CAMERA = 0


def _to_blob(array):
    """Serialize an (N,) numpy array of float64 to a COLMAP static matrix BLOB."""
    return np.asarray(array, dtype=np.float64).tobytes()


def populate_database_with_priors(workspace, sparse_dir, config):
    """Rewrite the COLMAP database structural tables with our poses + priors.

    After feature extraction, the DB holds keypoints/descriptors (indexed by the
    extractor's image ids) and per-image camera guesses. Here we drop the
    extractor's structural rows and re-create them from cameras.txt / images.txt
    (known intrinsics and poses) while keeping the extractor's image ids for
    keypoints to still line up. Finally we insert one pose prior per image:
    the camera projection center (world coordinates) plus a position
    covariance derived from the `pose_prior_weight` config value.

    Args:
        workspace: Workspace directory
        sparse_dir: Path to sparse/0 directory with prior poses
        config: Configuration dictionary
    """
    refinement_cfg = config.get("pose_refinement", {})
    pose_prior_weight = float(refinement_cfg.get("pose_prior_weight", 1.0))

    database_path = workspace / "database.db"
    cameras = _parse_cameras_txt(sparse_dir / "cameras.txt")
    images = _parse_images_txt(sparse_dir / "images.txt")
    if not cameras:
        raise RuntimeError(f"No cameras parsed from {sparse_dir / 'cameras.txt'}")
    if not images:
        raise RuntimeError(f"No images parsed from {sparse_dir / 'images.txt'}")

    # Position std. dev. (metres). `pose_prior_weight` scales how strictly the
    # priors are enforced: sigma = 1 / weight  ->  weight=1 -> 1.0 m, 10 -> 0.1 m.
    if pose_prior_weight > 0:
        sigma_m = 1.0 / pose_prior_weight
    else:
        sigma_m = 100.0  # essentially free
    cov_diag = sigma_m * sigma_m
    position_cov = np.eye(3) * cov_diag

    conn = sqlite3.connect(str(database_path))
    conn.execute("PRAGMA foreign_keys = OFF")
    cur = conn.cursor()

    # DB image id is the feature extractor's id, keyed by file name.
    name_to_db_image_id = {row[1]: row[0] for row in cur.execute("SELECT image_id, name FROM images")}

    # --- rebuild structural tables -------------------------------------------
    for table in ("pose_priors", "rig_sensors", "frames", "frame_data", "rigs",
                  "images", "cameras"):
        try:
            cur.execute(f"DELETE FROM {table}")
        except sqlite3.OperationalError:
            pass  # table may not exist in this schema version

    # cameras (known intrinsics, using our camera ids)
    for camera_id, (model, width, height, params) in cameras.items():
        model_id = CAMERA_MODEL_TO_ID.get(model)
        if model_id is None:
            raise RuntimeError(f"Unsupported camera model: {model}")
        cur.execute(
            "INSERT INTO cameras (camera_id, model, width, height, params, prior_focal_length) "
            "VALUES (?, ?, ?, ?, ?, ?)",
            (camera_id, model_id, width, height, _to_blob(params), 0),
        )

    # a rig per camera (single camera sensor rigs)
    # Note: rig_sensors is intentionally left empty — COLMAP treats
    # rig.ref_sensor_id as the ref sensor implicitly. Inserting it
    # again would cause a duplicate-sensor assertion failure.
    for camera_id in cameras:
        cur.execute(
            "INSERT INTO rigs (rig_id, ref_sensor_id, ref_sensor_type) VALUES (?, ?, ?)",
            (camera_id, camera_id, SENSOR_TYPE_CAMERA),
        )

    # images (keep extractor image ids so keypoints stay valid) + frames + frame_data
    for row in images:
        db_image_id = name_to_db_image_id.get(row["name"])
        if db_image_id is None:
            raise RuntimeError(f"Image '{row['name']}' not found in the feature DB")
        cur.execute(
            "INSERT INTO images (image_id, name, camera_id) VALUES (?, ?, ?)",
            (db_image_id, row["name"], row["camera_id"]),
        )
        cur.execute(
            "INSERT INTO frames (frame_id, rig_id) VALUES (?, ?)",
            (db_image_id, row["camera_id"]),
        )
        cur.execute(
            "INSERT INTO frame_data (frame_id, data_id, sensor_id, sensor_type) "
            "VALUES (?, ?, ?, ?)",
            (db_image_id, db_image_id, row["camera_id"], SENSOR_TYPE_CAMERA),
        )

    # --- purge stale data rows ------------------------------------------------
    # The extractor/matcher may have run on more images than survive in
    # images.txt. Rows for images that no longer exist in the DB break the
    # mapper's cache load: DatabaseCache::Load resolves every two_view_geometry
    # pair via image_to_frame_id.at() (std::out_of_range) and dies silently
    # right after "Loading images...". Matches are recomputed by match_features
    # (runs after this function), so clearing them is safe.
    cur.execute("DELETE FROM matches")
    cur.execute("DELETE FROM two_view_geometries")
    cur.execute(
        "DELETE FROM keypoints WHERE image_id "
        "NOT IN (SELECT image_id FROM images)")
    cur.execute(
        "DELETE FROM descriptors WHERE image_id "
        "NOT IN (SELECT image_id FROM images)")

    # --- pose priors ----------------------------------------------------------
    # Quaternion (w x y z) + tvec encode world->camera: p_cam = R p_world + t.
    # Camera projection center in world coords: C = -R^T t.
    gravity = np.array([np.nan, np.nan, np.nan])
    n_priors = 0
    for row in images:
        qw, qx, qy, qz = row["qvec"]
        n = math.sqrt(qw * qw + qx * qx + qy * qy + qz * qz)
        if n < 1e-12:
            continue
        qw, qx, qy, qz = qw / n, qx / n, qy / n, qz / n
        R = np.array([
            [1 - 2 * (qy * qy + qz * qz), 2 * (qx * qy - qz * qw), 2 * (qx * qz + qy * qw)],
            [2 * (qx * qy + qz * qw), 1 - 2 * (qx * qx + qz * qz), 2 * (qy * qz - qx * qw)],
            [2 * (qx * qz - qy * qw), 2 * (qy * qz + qx * qw), 1 - 2 * (qx * qx + qy * qy)],
        ], dtype=np.float64)
        center = -R.T @ row["tvec"]

        db_image_id = name_to_db_image_id[row["name"]]
        cur.execute(
            "INSERT INTO pose_priors (corr_data_id, corr_sensor_id, corr_sensor_type, "
            "position, position_covariance, coordinate_system, gravity) "
            "VALUES (?, ?, ?, ?, ?, ?, ?)",
            (
                db_image_id,
                row["camera_id"],  # corr_sensor_id = camera id
                SENSOR_TYPE_CAMERA,
                _to_blob(center),
                _to_blob(position_cov),
                1,  # CARTESIAN
                _to_blob(gravity),
            ),
        )
        n_priors += 1

    conn.commit()
    conn.close()

    print(f"✓ Database rebuilt: {len(cameras)} cameras, {len(images)} images, {n_priors} pose priors")


def match_features(colmap_exe, workspace, config):
    """Run COLMAP feature matching (sequential or exhaustive)."""
    refinement_cfg = config.get("pose_refinement", {})
    matching_mode = refinement_cfg.get("matching_mode", "sequential")

    database_path = workspace / "database.db"
    max_dist = config.get("max_frustum_distance", 10.0)

    if matching_mode == "sequential":
        cmd_args = [
            "sequential_matcher",
            "--database_path", str(database_path),
            "--SequentialMatching.overlap", "10",
        ]
        description = "Sequential matching"

    elif matching_mode == "exhaustive":
        cmd_args = [
            "exhaustive_matcher",
            "--database_path", str(database_path),
        ]
        description = "Exhaustive matching"

    elif matching_mode == "spatial":
        # Spatial matching pairs cameras by their pose-prior world positions
        # (distance in metres), instead of by frame order. This is the right
        # choice for a multi-sensor car rig, where consecutive frames point in
        # different directions and never overlap.
        pair_distance = config.get("pose_refinement", {}).get(
            "spatial_pair_distance", max_dist * 1.5)
        cmd_args = [
            "spatial_matcher",
            "--database_path", str(database_path),
            "--SpatialMatching.max_distance", str(pair_distance),
            "--SpatialMatching.ignore_z", "0",
        ]
        description = "Spatial matching (pose-prior camera distance)"

    else:
        raise ValueError(
            f"Unknown matching_mode: {matching_mode}. "
            f"Supported: 'sequential', 'exhaustive', 'spatial'"
        )

    run_colmap_command(colmap_exe, cmd_args, description)


def run_pose_prior_mapper(colmap_exe, workspace, images_dir, config):
    """Run COLMAP's dedicated pose_prior_mapper on the priors-populated DB.

    This is the COLMAP 4.1-dev entry point that sets `Mapper.use_prior_position
    = true` internally. It runs incremental SfM on the image features, aligns
    the reconstruction onto the prior camera centers (RANSAC-Sim3) the first
    time ≥ 3 frames are registered, and keeps refining poses under the priors.

    Args:
        colmap_exe: Path to COLMAP executable
        workspace: Workspace directory
        images_dir: Path to images directory
        config: Configuration dictionary
    """
    refinement_cfg = config.get("pose_refinement", {})
    max_iterations = refinement_cfg.get("max_refinement_iterations", 100)

    database_path = workspace / "database.db"
    output_path = workspace / "refined"
    output_path.mkdir(exist_ok=True)

    cmd_args = [
        "pose_prior_mapper",
        "--database_path", str(database_path),
        "--image_path", str(images_dir),
        "--output_path", str(output_path),
        "--Mapper.ba_refine_focal_length", "0",     # Lock intrinsics from
        "--Mapper.ba_refine_principal_point", "0",  #   interior orientation
        "--Mapper.ba_refine_extra_params", "0",
        "--Mapper.ba_local_max_num_iterations", str(max_iterations),
        "--Mapper.ba_global_max_num_iterations", str(max_iterations),
        # Relaxed init thresholds — strong pose priors compensate, so
        # we can allow weaker geometry to bootstrap registration.
        "--Mapper.init_min_num_inliers", "30",       # default 100
        "--Mapper.init_min_tri_angle", "5",          # default 16°
        "--Mapper.init_num_trials", "500",           # default 200
        "--Mapper.abs_pose_min_num_inliers", "10",   # default 30
        "--Mapper.abs_pose_min_inlier_ratio", "0.10",# default 0.25
        "--Mapper.min_model_size", "5",              # default 10
    ]

    run_colmap_command(colmap_exe, cmd_args, "Bundle adjustment with pose priors")

    refined_model = output_path / "0"
    if not refined_model.exists():
        raise RuntimeError("COLMAP mapper did not produce output model")


