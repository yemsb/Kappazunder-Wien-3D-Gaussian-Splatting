#!/usr/bin/env python3
"""
Refine camera poses using COLMAP bundle adjustment with pose priors.

This script integrates COLMAP's feature extraction, matching, and mapper into
the Kappazunder pipeline to refine the original GNSS/INS camera poses while
preserving georeferencing. The refined poses stay in the same coordinate frame
as the LiDAR point cloud, so no additional alignment is needed.

Workflow:
1. Load existing cameras.txt and images.txt (from build_colmap_selection.py)
2. Run COLMAP feature extraction on selected images
3. Rewrite COLMAP database structural tables (cameras/images/frames/rigs)
   from our cameras.txt/images.txt, and insert camera poses as pose priors
4. Run COLMAP feature matching
5. Run `pose_prior_mapper` (COLMAP 4.1 dev rig-based build):
   - deduplicated incremental SfM on the image features
   - RANSAC-Sim3 alignment of the reconstruction onto the prior camera centers
   - bundle adjustment under the position priors (georeferencing preserved)
6. Replace COLMAP's triangulated points with the LiDAR `points3D.ply`
7. Export refined cameras and images in the original coordinate frame

Author: Generated by Claude Code
Date: 2026-09-16
"""

